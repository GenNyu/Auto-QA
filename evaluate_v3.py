# ─────────────────────────────────────────────

def parse_llm_response(response_text: str) -> Dict:
    """Extract and parse JSON from LLM response. Handles truncated responses gracefully."""
    if not response_text:
        raise ValueError("Empty response from LLM")

    text = re.sub(r'^```(?:json)?\s*', '', response_text.strip(), flags=re.IGNORECASE)
    text = re.sub(r'\s*```$', '', text.strip())

    try:
        return json.loads(text)
    except json.JSONDecodeError:
        pass

    json_match = re.search(r'\{.*\}', text, re.DOTALL)
    if json_match:
        try:
            return json.loads(json_match.group(0))
        except json.JSONDecodeError:
            pass

    salvaged = _salvage_truncated_json(text)
    if salvaged:
        return salvaged

    raise ValueError(f"Cannot parse JSON from response: {text[:200]}")


def _salvage_truncated_json(text: str) -> Optional[Dict]:
    start = text.find('{')
    if start == -1:
        return None

    fragment = text[start:]
    depth_obj = 0
    depth_arr = 0
    in_string = False
    i = 0
    while i < len(fragment):
        c = fragment[i]
        if c == '\\' and in_string:
            i += 2
            continue
        if c == '"':
            in_string = not in_string
        elif not in_string:
            if c == '{':
                depth_obj += 1
            elif c == '}':
                depth_obj -= 1
            elif c == '[':
                depth_arr += 1
            elif c == ']':
                depth_arr -= 1
        i += 1

    suffix = ''
    if in_string:
        suffix += '"'
    suffix += ']' * depth_arr
    trimmed = (fragment + suffix).rstrip()
    if trimmed.endswith(','):
        trimmed = trimmed[:-1]
    suffix_final = '}}' if depth_obj > 1 else ('}' if depth_obj >= 1 else '')
    candidate = trimmed + suffix_final

    try:
        result = json.loads(candidate)
        result['_truncated'] = True
        return result
    except json.JSONDecodeError:
        return None


def call_llm(
    provider: LLMProvider,
    provider_name: str,
    item: Dict,
    temperature: float,
    system: str = SYSTEM_PROMPT,
    prompt_override: Optional[str] = None,
    max_tokens: int = 2000,
) -> Dict:
    """Call LLM for semantic evaluation. Returns parsed JSON dict."""
    prompt = prompt_override if prompt_override is not None else build_user_prompt(item)
    messages = build_messages(provider_name, prompt, system=system)

    response_text = provider.chat(
        messages,
        temperature=temperature,
        max_tokens=max_tokens,
    )

    try:
        return parse_llm_response(response_text)
    except Exception as e:
        raise ValueError(f"Invalid JSON response: {e}\nRaw: {response_text[:300]}")


def extract_claims(
    provider: LLMProvider,
    provider_name: str,
    item: Dict,
    temperature: float,
) -> List[str]:
    """
    Identify specific factual claims in the AI answer that go BEYOND what the expected answer provides.
    Returns a list of claim strings, or [] on failure.
    """
    prompt = build_user_prompt_claim_extractor(item)
    messages = build_messages(provider_name, prompt, system=SYSTEM_PROMPT_CLAIM_EXTRACTOR)

    response_text = provider.chat(
        messages,
        temperature=temperature,
        max_tokens=1000,
    )

    try:
        result = parse_llm_response(response_text)
        claims = result.get("extra_claims", [])
        return [str(c) for c in claims if c]
    except Exception:
        return []


