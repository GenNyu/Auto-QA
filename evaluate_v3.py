# JOIN MODE (QA + PCI BY ID)
# ─────────────────────────────────────────────

def build_joined_items(config: EvaluatorConfig) -> List[Dict]:
    """Join QA output with PCI filtered data by id."""
    if not config.qa_file or not config.pci_file:
        raise ValueError("qa_file and pci_file are required for join mode")

    qa_path = Path(config.qa_file)
    pci_path = Path(config.pci_file)
    if not qa_path.exists():
        raise FileNotFoundError(f"QA file not found: {qa_path}")
    if not pci_path.exists():
        raise FileNotFoundError(f"PCI file not found: {pci_path}")

    qa_data = json.loads(qa_path.read_text(encoding="utf-8"))
    pci_data = json.loads(pci_path.read_text(encoding="utf-8"))

    pci_by_id = {}
    for row in pci_data:
        pid = str(row.get(config.id_field, "")).strip()
        if pid:
            pci_by_id[pid] = row

    joined: List[Dict] = []
    missing = 0
    for row in qa_data:
        qid = str(row.get(config.id_field, "")).strip()
        if not qid:
            missing += 1
            continue
        pci_row = pci_by_id.get(qid)
        if not pci_row:
            missing += 1
            continue

        context_val = pci_row.get(config.context_field, "")
        if (not str(context_val).strip()) and config.context_field != "pci_dss_requirements":
            # Fallback for PCI filtered files that store context in pci_dss_requirements
            context_val = pci_row.get("pci_dss_requirements", "")

        joined.append({
            "id": qid,
            "question": row.get("question", ""),
            "answer": row.get("answer", ""),
            "context": context_val,
            "main_content": pci_row.get(config.main_field, ""),
            "check": pci_row.get(config.expected_field, ""),
            "source": row.get("source", []),
        })

    if missing > 0:
        print(f"⚠ join mode: skipped {missing} item(s) due to missing id or PCI match")

    return joined

# ─────────────────────────────────────────────
# PROCESS ITEM (3-step: Pass1 → Claim Extract → Pass2)
# ─────────────────────────────────────────────

def process_item(
    provider: LLMProvider,
    provider_name: str,
    config: EvaluatorConfig,
    item: Dict,
    idx: int,
) -> None:
    """
    Evaluate a single compliance test item.

    Step 1 — Pass 1   : evaluate AI Answer vs Expected Answer
    Step 2 — Extract  : if 5 <= score <= threshold, extract extra claims from AI Answer beyond Expected Answer
    Step 3 — Pass 2   : verify each extra claim against the full KB source file and re-evaluate

    Items with score ≤ 4 are not rechecked because the answer is already clearly incorrect.
    """
    try:
        nli = call_llm(provider, provider_name, item, config.temperature)
        score = int(nli.get("score", 0) or 0)
        label = nli.get("label", "UNKNOWN")
        confidence = float(nli.get("confidence", 0) or 0)

        item["pass1_score"] = score
        item["pass1_check"] = nli.get("reason", "")
        item["rechecked"] = False

        print(f"[{idx}] Pass1 → {label} (score: {score}, conf: {confidence:.2f})", end="")

        should_recheck = (
            config.pass2_enabled
            and (5 <= score <= config.recheck_threshold)
            and bool(config.kb_dir)
        )

        if not should_recheck:
            if score <= 4 and config.kb_dir:
                print(f"  →  pass2 skipped (clearly incorrect, score={score})")
            else:
                print()
        else:
            file_name = str(item.get("file") or "").strip()
            if not file_name:
                print("  →  skipped (no file field)")
            else:
                file_content = read_kb_file(file_name, config.kb_dir)
                if not file_content:
                    print(f"  →  skipped (file not found: {file_name})")
                else:
                    extra_claims = extract_claims(provider, provider_name, item, config.temperature)

                    MAX_CLAIMS = 15
                    if len(extra_claims) > MAX_CLAIMS:
                        print(f"  →  {len(extra_claims)} extra claim(s) (capped to {MAX_CLAIMS})", end="")
                        extra_claims = extra_claims[:MAX_CLAIMS]
                    else:
                        print(f"  →  {len(extra_claims)} extra claim(s)", end="")

                    pass2_max_tokens = min(500 + len(extra_claims) * 150, 4000)
                    pass2_prompt = build_user_prompt_pass2(item, file_content, extra_claims)
                    nli2 = call_llm(
                        provider,
                        provider_name,
                        item,
                        config.temperature,
                        system=SYSTEM_PROMPT_PASS2,
                        prompt_override=pass2_prompt,
                        max_tokens=pass2_max_tokens,
                    )

                    if nli2.get("_truncated"):
                        print(" ⚠ truncated", end="")
                    score2 = int(nli2.get("score", 0) or 0)
                    label2 = nli2.get("label", "UNKNOWN")
                    conf2 = float(nli2.get("confidence", 0) or 0)

                    pass1_score = item["pass1_score"]
                    score2 = max(score2, pass1_score)
                    nli2["score"] = score2

                    print(f"  →  Pass2 → {label2} (score: {score2}, conf: {conf2:.2f})")

                    nli = nli2
                    score = score2
                    item["rechecked"] = True
                    item["extra_claims"] = extra_claims
                    item["pass2_score"] = score2
                    item["pass2_check"] = nli2.get("reason", "")
                    item["pass2_verified_claims"] = nli2.get("verified_claims", [])

        item["evaluate"] = map_score_to_evaluate(score)
        item["score"] = score
        item["eval_reason"] = nli.get("reason", "")

    except Exception as e:
        item["evaluate"] = "error"
        item["score"] = 0
        item["eval_reason"] = str(e)
        item["rechecked"] = False
        print(f"\n[{idx}] ERROR → {e}")


# ─────────────────────────────────────────────
# EVALUATION LOOP
# ─────────────────────────────────────────────

def run_evaluation(config: EvaluatorConfig, provider: LLMProvider, provider_name: str) -> None:
    """Main evaluation loop."""
    input_path = Path(config.input_path)
    output_path = Path(config.output_path) if config.output_path else input_path.with_name(f"{input_path.stem}_semantic_scored.json")

    if config.qa_file and config.pci_file:
        data = build_joined_items(config)
        if not config.output_path:
            output_path = input_path.with_name(f"{input_path.stem}_joined_scored.json")
    else:
        data = json.loads(input_path.read_text(encoding="utf-8"))
    total = len(data)

    print(f"Loaded   : {input_path.name}")
    print(f"Total    : {total}")
    print(f"Provider : {provider_name.upper()}")
    if config.base_url:
        print(f"URL      : {config.base_url}")
    if config.model:
        print(f"Model    : {config.model}")
    if config.qa_file and config.pci_file:
        print(f"Join     : {config.qa_file}  +  {config.pci_file}")
        print(f"Fields   : context='{config.context_field}', main='{config.main_field}', expected='{config.expected_field}', id='{config.id_field}'")
    if config.kb_dir:
        if config.pass2_enabled:
            print(f"KB dir   : {config.kb_dir}  (2-pass enabled for score ≤ {config.recheck_threshold})")
        else:
            print(f"KB dir   : {config.kb_dir}  (2-pass disabled via --pass2 off)")
    else:
        print("KB dir   : not set  (1-pass only)")
    print()

    for idx, item in enumerate(data, start=1):
        process_item(provider, provider_name, config, item, idx)
        if idx < total:
            time.sleep(config.sleep_time)

    output_path.write_text(
        json.dumps(data, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )

    print(f"\n{'='*80}")
    print_statistics(data)
    print(f"\n✅ Saved to: {output_path}")


